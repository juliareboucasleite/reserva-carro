const translations = { pt: dict.pt, en } as const;

export type Lang = keyof typeof translations;
export type Translation = (typeof translations)['pt'];

type Ctx = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: Translation;
};

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('pt');

  useEffect(() => {
    SecureStore.getItemAsync(LANG_KEY).then((stored) => {
      if (stored === 'pt' || stored === 'en') setLangState(stored);
    });
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    SecureStore.setItemAsync(LANG_KEY, next).catch(() => undefined);
  }, []);

  const value = useMemo<Ctx>(
    () => ({ lang, setLang, t: translations[lang] }),
    [lang, setLang],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be inside I18nProvider');
  return ctx;
}

export function formatTemplate(template: string, vars: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined ? String(vars[key]) : `{${key}}`,
  );
}

export function formatCurrency(value: number, lang: Lang) {
  const locale = lang === 'pt' ? 'pt-PT' : 'en-GB';
  const amount = value.toLocaleString(locale, {
    minimumFractionDigits: value % 1 === 0 ? 0 : 2,
    maximumFractionDigits: 2,
  });
  return `${amount} €`;
}

export function formatKm(value: number | null | undefined, lang: Lang) {
  if (value === null || value === undefined) return '—';
  const locale = lang === 'pt' ? 'pt-PT' : 'en-GB';
  return `${value.toLocaleString(locale)} km`;
}
